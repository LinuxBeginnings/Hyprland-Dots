# Patch: drop a UserConfigs/monitors.lua that the display system generated with
# a highres mode, so the shipped defaults take over on an upgraded install.
#
# The v2.3.28 display-layout feature wrote the layout it applied to
# UserConfigs/monitors.lua on EVERY apply, including the boot-time `auto`, and
# its generated layout asked for the LARGEST mode a monitor advertises. On a VM
# that pinned Virtual-1 to 5120x2440@50, and because that file is loaded last by
# lua/monitors.lua and read first by user_laptops.lua it also overrode both the
# shipped `Virtual-1 = 1920x1080@60` rule and anything the user wrote by hand.
#
# The code no longer does either: `auto` does not persist, and generation follows
# the mode already on screen. What this patch fixes is the file left behind on an
# install that already ran the old code. copy.sh only ADDS missing UserConfigs
# files, so nothing else would ever replace it.
#
# It only ever removes a file that carries the generator marker, i.e. one WE
# wrote - a user's own monitors.lua (or the shipped template) has no marker and
# is left alone. A generated file is reproducible: the layouts the user saved
# live in UserConfigs/display-layouts.json, which `auto` re-resolves from, and
# with no marker the file would otherwise be treated as the user's own and never
# written again.
#
# The reset is done ONCE, guarded by a sentinel. Without it, a layout the user
# applies on a later version would be deleted by the next upgrade.

# shellcheck source=./lib.sh
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib.sh"

USERCONFIGS="$(patch_hypr_dir)/UserConfigs"
TARGET="$USERCONFIGS/monitors.lua"
SENTINEL="$USERCONFIGS/.display-profile-monitors-lua-reset"
MARKER='Generated by DisplayProfile.sh'

# Never invent a config tree: with no UserConfigs there is nothing installed to
# patch, and no sentinel to leave behind either.
if [ ! -d "$USERCONFIGS" ]; then
  patch_log "UserConfigs not installed; skipping the generated monitors.lua reset"
  exit 0
fi

if [ -f "$SENTINEL" ]; then
  patch_log "the generated monitors.lua reset has already run; nothing to do"
  exit 0
fi

# From here on the reset counts as done whatever happens, so a layout the user
# applies later is never mistaken for the stale file this patch is about.
if [ ! -f "$TARGET" ]; then
  patch_log "UserConfigs/monitors.lua is absent; nothing to reset"
  : >"$SENTINEL" 2>/dev/null || true
  exit 0
fi

if ! grep -qF -- "$MARKER" "$TARGET" 2>/dev/null; then
  patch_log "UserConfigs/monitors.lua is not a generated file; leaving it alone"
  : >"$SENTINEL" 2>/dev/null || true
  exit 0
fi

# Back it up beside itself, with a name that is NOT .lua so it is never loaded by
# lua/monitors.lua nor swept by the config's Lua syntax check.
backup="$TARGET.generated-backup-$(date +%Y%m%d-%H%M%S)"
if cp -f -- "$TARGET" "$backup" 2>/dev/null && [ -s "$backup" ]; then
  rm -f -- "$TARGET"
  patch_log "removed the generated UserConfigs/monitors.lua (backup: $(basename "$backup"))"
  patch_log "  it asked for the largest mode the monitor advertises; lua/monitors.lua now supplies"
  patch_log "  preferred plus the explicit per-output rules, and saved layouts stay in display-layouts.json"
else
  rm -f -- "$backup" 2>/dev/null || true
  patch_log "could not back UserConfigs/monitors.lua up; left it in place"
  patch_log "  delete the file, or its 'Generated by DisplayProfile.sh' marker line, to take it over by hand"
fi

: >"$SENTINEL" 2>/dev/null || true
exit 0
